#!/usr/bin/env python3
"""Cross-compile tinyarray 1.2.5 for HarmonyOS.

tinyarray is a hard import dependency of ``chimerax.atomic.cymol``. The sdist
generates ``src/version.hh`` at build time, so this tool writes it explicitly and
then compiles the single extension module with the HarmonyOS SDK clang.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import tarfile
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SDK = Path('/Applications/DevEco-Studio.app/Contents/sdk/default/openharmony/native')
VERSION = '1.2.5'
TRIPLE = 'aarch64-linux-ohos'
SUFFIX = 'cpython-311-aarch64-linux-ohos.so'


def sha256(path: Path) -> str:
    with path.open('rb') as handle:
        return hashlib.file_digest(handle, 'sha256').hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk', type=Path, default=DEFAULT_SDK)
    parser.add_argument('--archive', type=Path,
                        default=ROOT / f'build/downloads/tinyarray-{VERSION}.tar.gz')
    parser.add_argument('--cpython', type=Path,
                        default=ROOT / 'build/cpython-3.11.18/ohos-aarch64-with-libffi-linked')
    parser.add_argument('--packages', type=Path, default=ROOT / 'build/chimerax-python')
    parser.add_argument('--report', type=Path, default=None)
    args = parser.parse_args()
    day = datetime.now(timezone.utc).date().isoformat()
    report_path = args.report or ROOT / f'reports/tinyarray-{day}.json'
    report: dict = {'schema_version': 1, 'created_at_utc': datetime.now(timezone.utc).isoformat(),
                    'version': VERSION, 'target': TRIPLE}
    try:
        with tempfile.TemporaryDirectory(prefix='tinyarray-') as work:
            with tarfile.open(args.archive) as bundle:
                bundle.extractall(work, filter='data')
            source = Path(work) / f'tinyarray-{VERSION}'
            (source / 'src' / 'version.hh').write_text(
                f'// generated by tools/build_tinyarray_harmony.py\n'
                f'#define VERSION "{VERSION}"\n')
            clang = args.sdk / 'llvm/bin/clang++'
            target = args.packages / f'tinyarray.{SUFFIX}'
            command = [str(clang), f'--target={TRIPLE}', f'--sysroot={args.sdk / "sysroot"}',
                       '-std=c++11', '-O2', '-fPIC', '-shared',
                       f'-I{args.cpython / "source/Include"}', f'-I{args.cpython / "objects"}',
                       f'-I{args.packages / "numpy/core/include"}', f'-I{source / "src"}',
                       '-o', str(target), *[str(p) for p in sorted((source / 'src').glob('*.cc'))],
                       f'-L{args.cpython / "runtime/lib"}', '-l:libpython3.11.so.1.0',
                       '-Wl,-rpath,$ORIGIN/../lib']
            built = subprocess.run(command, capture_output=True, text=True)
            if built.returncode != 0:
                raise RuntimeError(built.stderr[-2000:])
            report.update({'path': str(target), 'bytes': target.stat().st_size,
                           'sha256': sha256(target),
                           'status': 'tinyarray_cross_compiled_not_target_tested'})
    except Exception as error:  # noqa: BLE001 - report the failure
        report['status'] = 'tinyarray_build_failed'
        report['error'] = str(error)[:3000]
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    print(report['status'], report.get('path', ''))
    return 0 if report['status'].startswith('tinyarray_cross_compiled') else 1


if __name__ == '__main__':
    raise SystemExit(main())
