#!/usr/bin/env python3
"""Generate ctypes signatures for the GL entry points ChimeraX calls.

The prototypes come from the OpenHarmony NDK's GLES3 headers, so the generated table is
exact instead of guessed. `_cxgl` uses it to declare argtypes/restype per function.
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_HEADERS = [
    Path('/Applications/DevEco-Studio.app/Contents/sdk/default/openharmony/native/sysroot'
         '/usr/include/GLES3/gl3.h'),
    Path('/Applications/DevEco-Studio.app/Contents/sdk/default/openharmony/native/sysroot'
         '/usr/include/GLES2/gl2.h'),
]

TYPE_MAP = {
    'void': None,
    'GLenum': 'ctypes.c_uint',
    'GLuint': 'ctypes.c_uint',
    'GLbitfield': 'ctypes.c_uint',
    'GLint': 'ctypes.c_int',
    'GLsizei': 'ctypes.c_int',
    'GLfloat': 'ctypes.c_float',
    'GLclampf': 'ctypes.c_float',
    'GLdouble': 'ctypes.c_double',
    'GLboolean': 'ctypes.c_ubyte',
    'GLintptr': 'ctypes.c_int64',
    'GLsizeiptr': 'ctypes.c_int64',
    'GLint64': 'ctypes.c_int64',
    'GLuint64': 'ctypes.c_uint64',
    'GLchar': 'ctypes.c_char',
    'GLubyte': 'ctypes.c_ubyte',
    'GLclampd': 'ctypes.c_double',
    'GLvoid': 'GLVOID_SENTINEL',
}

PROTOTYPE = re.compile(
    r'GL_APICALL\s+(?P<ret>.*?)\s*GL_APIENTRY\s+(?P<name>gl[A-Za-z0-9_]+)\s*'
    r'\((?P<args>[^;]*?)\)\s*;',
    re.MULTILINE | re.DOTALL)

# Names ChimeraX uses that map onto a different ES entry point.
ALIASES = {
    'glClearDepth': 'glClearDepthf',
    'glDepthRange': 'glDepthRangef',
    'glGetBoolean': 'glGetBooleanv',
    'glGetInteger': 'glGetIntegerv',
    'glGetDouble': 'glGetFloatv',
    'glPointSize': None,      # no ES equivalent: treated as a no-op
    'glPolygonMode': None,
    'glDrawBuffer': None,
    'glReadBuffer': None,
    'glLogicOp': None,
    'glGetTexImage': None,
    'glTexImage1D': None,
    'glTexSubImage1D': None,
    'glGetDebugMessageLog': None,
}


def used_functions(package: Path) -> list[str]:
    pattern = re.compile(r'GL\.(gl[A-Za-z0-9_]+)')
    names: set[str] = set()
    for path in package.rglob('*.py'):
        try:
            text = path.read_text(errors='replace')
        except OSError:
            continue
        names.update(pattern.findall(text))
    return sorted(names)


def strip_parameter_name(declaration: str) -> str:
    """Turn "GLuint array" into "GLuint" and "const GLchar *name" into "const GLchar *"."""
    tokens = declaration.split()
    if not tokens:
        return declaration
    last = tokens[-1]
    if len(tokens) > 1 and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', last):
        return ' '.join(tokens[:-1])
    # Pointer parameters are often written "*name"; drop the name but keep the stars.
    attached = re.fullmatch(r'(\*+)([A-Za-z_][A-Za-z0-9_]*)', last)
    if attached:
        tokens[-1] = attached.group(1)
        return ' '.join(tokens)
    return declaration


def parse_prototypes(headers) -> dict[str, tuple[str, list[str]]]:
    if isinstance(headers, Path):
        headers = [headers]
    text = '\n'.join(path.read_text(errors='replace') for path in headers if path.is_file())
    found: dict[str, tuple[str, list[str]]] = {}
    for match in PROTOTYPE.finditer(text):
        ret = ' '.join(match.group('ret').split())
        args_text = match.group('args').strip()
        if args_text in ('', 'void'):
            args: list[str] = []
        else:
            args = [strip_parameter_name(part) for part in args_text.split(',')]
        found[match.group('name')] = (ret, args)
    return found


def ctype_for(gl_type: str) -> str:
    pointer_depth = gl_type.count('*')
    base = gl_type.replace('const', ' ').replace('*', ' ').strip()
    base = ' '.join(base.split())
    if base in ('GLvoid', 'GLVOID_SENTINEL', 'void'):
        # GLvoid is Khronos' spelling of void.
        return 'ctypes.c_void_p' if pointer_depth else 'None'

    if pointer_depth == 0:
        if base not in TYPE_MAP:
            raise KeyError(base)
        return TYPE_MAP[base] or 'None'
    if pointer_depth == 1:
        if base == 'void':
            return 'ctypes.c_void_p'
        if base == 'GLchar':
            return 'ctypes.c_char_p'
        if base not in TYPE_MAP:
            raise KeyError(base)
        return 'ctypes.POINTER(%s)' % TYPE_MAP[base]
    # Pointer to pointer: glShaderSource's "const GLchar *const*"
    return 'ctypes.POINTER(ctypes.c_char_p)'


import json


def render(prototypes: dict[str, tuple[str, list[str]]], wanted: list[str]) -> str:
    lines = ['"""Generated by tools/generate_cxgl_signatures.py - do not edit by hand."""',
             'import ctypes', '', '# name: (argument types, return type)', 'SIGNATURES = {']
    missing: list[str] = []
    for name in wanted:
        if name not in prototypes:
            missing.append(name)
            continue
        ret, args = prototypes[name]
        try:
            arg_types = [ctype_for(arg) for arg in args]
            restype = ctype_for(ret)
        except KeyError:
            missing.append(name)
            continue
        lines.append('    %r: ([%s], %s),' % (name, ', '.join(arg_types), restype))
    lines.append('}')
    lines.append('}')
    lines.append('')
    lines.append('# name: the ES entry point to call, or None for a no-op')
    lines.append('ALIASES = %s' % (json.dumps(
        {name: ALIASES[name] for name in wanted if name in ALIASES}, indent=4),))
    lines.append('')
    lines.append('MISSING = %s' % (json.dumps(missing),))
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--header', type=Path, nargs='*', default=DEFAULT_HEADERS)
    parser.add_argument('--output', type=Path,
                        default=ROOT / 'vendor/graphics/_cxgl_sigs.py')
    parser.add_argument('--report', type=Path, default=ROOT / 'reports/cxgl-signatures.json')
    args = parser.parse_args()

    package = ROOT / 'build/chimerax-python/chimerax'
    wanted = used_functions(package) if package.is_dir() else []
    prototypes = parse_prototypes(args.header)
    source = render(prototypes, wanted)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source)

    missing_line = re.search(r'^MISSING = (\[.*\])$', source, re.MULTILINE)
    missing = json.loads(missing_line.group(1)) if missing_line else []
    report = {
        'functions_used': len(wanted),
        'functions_covered': len(wanted) - len(missing),
        'missing': missing,
        'header': str(args.header),
        'output': str(args.output),
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
